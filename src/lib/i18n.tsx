type Ctx = {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: Key, vars?: Vars) => string
  tn: (one: Key, other: Key, n: number) => string
  te: (e: unknown) => string
  teRaw: (e: unknown) => string
}

function fill(s: string, vars?: Vars): string {
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}

function initialLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY)
    if (v === 'en' || v === 'hi') return v
  } catch {
    /* ignore */
  }
  return 'en'
}

const I18nContext = createContext<Ctx | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)

  useEffect(() => {
    document.documentElement.lang = lang
    // The Android / Windows app show some notifications themselves: tell them the language (v18).
    const w = window as unknown as { PQ?: { setLang?: (l: string) => void }; PQDesktop?: { setLang?: (l: string) => void } }
    try { w.PQ?.setLang?.(lang) } catch { /* old app */ }
    try { w.PQDesktop?.setLang?.(lang) } catch { /* old app */ }
  }, [lang])

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem(STORAGE_KEY, l)
    } catch {
      /* ignore */
    }
    // Push tokens are re-saved with the new language (lib/push.ts listens).
    try { window.dispatchEvent(new CustomEvent('pq-lang', { detail: l })) } catch { /* ignore */ }
  }, [])

  const value = useMemo<Ctx>(() => {
    const dict = DICTS[lang]
    const t = (key: Key, vars?: Vars) => fill(dict[key] ?? en[key], vars)
    const tn = (one: Key, other: Key, n: number) => t(n === 1 ? one : other, { n })
    const te = (e: unknown) => {
      const raw = errMsg(e)
      const mb = /^this shop accepts up to (\d+) mb per order/i.exec(raw.trim())
      if (mb) return t('uOrderTooBig', { mb: mb[1] })
      if ((typeof navigator !== 'undefined' && navigator.onLine === false) || /failed to fetch|networkerror|load failed|network request failed|fetch failed/i.test(raw)) return t('errOffline')
      if (/permission denied for (table|relation|schema)|jwt expired|invalid jwt|jwt.*(malformed|invalid)/i.test(raw)) return t('errSession')
      const k = SERVER_ERRORS[raw.trim().replace(/\.$/, '').toLowerCase()]
      if (k) return t(k)
      const pdf = /^could not read the pages of (.+?)\.?$/i.exec(raw.trim())
      if (pdf) return t('errPdfRead', { name: pdf[1] })
      const ft = /^file type not allowed: ([^.]+)\./i.exec(raw.trim())
      if (ft) return t('errFileType', { ext: ft[1] })
      // Supabase Auth: pick the line by its error code, never show its English text as is.
      const ae = e as { name?: string; status?: number; code?: string } | null
      const ak = AUTH_ERRORS[String(ae?.code || '')]
      if (ak) return t(ak)
      if (ae && /^Auth/.test(String(ae.name || '')) && Number(ae.status) === 429) return t('errTooManyTries')
      // Anything else (an unknown server line, database / network / library internals): one friendly line for
      // shop owners and customers. The real text goes to the console; the admin panel uses teRaw to see it.
      try { console.error('[PrintQR error]', e) } catch { /* ignore */ }
      return t('errGeneric')
    }
    /** Admin panel only: the real server text (admins need it to fix things). */
    const teRaw = (e: unknown) => errMsg(e)
    return { lang, setLang, t, tn, te, teRaw }
  }, [lang, setLang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): Ctx {
  const c = useContext(I18nContext)
  if (!c) throw new Error('useI18n must be used inside I18nProvider')
  return c
}
